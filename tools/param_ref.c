/* The manual's parameter reference (book/manual/parameters.md), from the firmware's own table (sy_param.c SP[]):
 * every sound parameter, its section, its range and default as the screen shows them (sy_text.c sp_text), whether
 * the matrix can move it and its MIDI CC. Run by tools/gen_param_ref.sh; never edit its output by hand. */
#define SY_TICKS() 0u
#define SY_TICKS_BLK 17408u
#define SY_ENGINE 1
#include "../tests/sy_host.h"

/* the firmware's texts are Latin-1 (the degree sign 0xB0, as its fonts have it): as UTF-8 for the book */
static const char *u8(const char *s, char *out)
{
    char *o = out;
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c < 0x80u) {
            *o++ = (char)c;
        } else {
            *o++ = (char)(0xC0u | (c >> 6));
            *o++ = (char)(0x80u | (c & 0x3Fu));
        }
    }
    *o = 0;
    return out;
}

int main(void)
{
    uint32_t s, id, n = 0;
    char lo[32], hi[32], df[32], cc[8], u[5][64];
    printf("# Parameter reference\n\n");
    printf("<!-- generated by tools/gen_param_ref.sh from firmware/src/sy_param.c: do not edit by hand -->\n\n");
    printf("Every parameter a Strata sound stores, by section, as the screen shows it. **Mod**: the matrix (and the\n"
           "assign window) can move it. **CC**: the MIDI control change that sets it without MIDI LEARN (none: -).\n"
           "The drums, the looper and the settings keep their own values: see their chapters.\n\n");
    for (s = 0; s < SEC_COUNT; s++) {
        uint32_t any = 0;
        for (id = 0; id < SP_COUNT; id++) {
            if (SP[id].sec != s || (SP[id].flags & F_OLD))
                continue;
            if (!any) {
                printf("## %s\n\n| Parameter | Range | Default | Mod | CC |\n|---|---|---|:-:|:-:|\n", u8(SEC_NAMES[s], u[0]));
                any = 1;
            }
            sp_text(id, SP[id].lo, lo);
            sp_text(id, SP[id].hi, hi);
            sp_text(id, SP[id].def, df);
            snprintf(cc, sizeof cc, "%u", (unsigned)SP[id].cc);
            printf("| %s | %s .. %s | %s | %s | %s |\n", u8(SP[id].name, u[1]), u8(lo, u[2]), u8(hi, u[3]),
                   u8(df, u[4]), (SP[id].flags & F_MOD) ? "yes" : "", SP[id].cc ? cc : "-");
            n++;
        }
        if (any)
            printf("\n");
    }
    printf("_%u parameters._\n", (unsigned)n);
    return 0;
}
